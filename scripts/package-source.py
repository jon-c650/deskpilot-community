"""Build a fail-closed source archive from the exact compiled project graph.
No git archive, vendor archives, executables, DLLs, profiles or signing keys.
"""
from pathlib import Path
import xml.etree.ElementTree as ET,json,hashlib,zipfile,os,sys
repo=Path(__file__).resolve().parent.parent
ns={'m':'http://schemas.microsoft.com/developer/msbuild/2003'}
projects=set();inputs=set();generated=set()
def add(path,required=True):
 p=Path(path).resolve()
 if not p.is_relative_to(repo):raise RuntimeError('Source input escapes repository: '+str(p))
 if not p.exists():
  if required:raise RuntimeError('Missing source input: '+str(p.relative_to(repo)))
  return
 if p.suffix.lower() in ['.dll','.exe','.pfx','.snk','.mdf','.ldf','.msi','.zip','.7z','.nupkg','.obj','.pdb','.res','.lib','.ilk','.exp']:
  if p.suffix.lower() in ['.dll','.exe']:generated.add(str(p.relative_to(repo)));return
  raise RuntimeError('Refusing binary/data/key archive: '+str(p.relative_to(repo)))
 inputs.add(p)
def project(path):
 p=Path(path).resolve()
 if p in projects:return
 projects.add(p);add(p);tree=ET.parse(p)
 for item in tree.findall('.//m:ProjectReference',ns):project(p.parent/item.get('Include').replace('\\','/'))
 for tag in ['Compile','EmbeddedResource','EntityDeploy','ApplicationIcon','ApplicationManifest']:
  entries=tree.findall('.//m:'+tag,ns)
  for item in entries:
   name=item.get('Include') or item.text
   if not name:continue
   target=p.parent/name.replace('\\','/');add(target)
   if target.suffix.lower()=='.resx':
    for data in ET.parse(target).getroot().findall('data'):
     if 'ResXFileRef' in data.get('type',''):
      name=data.findtext('value','').split(';')[0]
      add(target.parent/name.replace('\\','/'))
 for item in tree.findall('.//m:Reference/m:HintPath',ns):
  value=item.text.replace('\\','/')
  # Framework/NuGet/OS interop/PuTTY binaries are retrieved/generated by the recipe.
  add(p.parent/value,required=False)
 for tag in ['Content','None']:
  for item in tree.findall('.//m:'+tag,ns):
   if item.find('m:CopyToOutputDirectory',ns) is not None:add(p.parent/item.get('Include').replace('\\','/'))
 for name in ['app.config','packages.config']:
  if (p.parent/name).exists():add(p.parent/name)
for name in ['Terminals','Terminals.Plugins.Rdp','Terminals.Plugins.Putty','Terminals.Plugins.Web']:
 project(repo/'upstream/Terminals/Source'/name/(name+'.csproj'))
for folder in ['scripts','packaging','helpers/WireGuardProfiles','branding','docs/licenses','docs/release']:
 for p in (repo/folder).rglob('*'):
  if p.is_file() and not any(x in p.parts for x in ['__pycache__','bin','obj']):add(p)
add(repo/'upstream/Terminals/Resources/Database/Terminals_CreateDatabase_v3.0.sql')
for name in ['upstream/Terminals/LICENSE.md','.github/workflows/windows-baseline.yml','docs/ui/WINDOWS-PREVIEW.md']:
 add(repo/name)
# Default app configuration is a build input, not a copied Windows user profile.
# No Source/TabControl, copied utility implementations, vendor libraries or raw
# historical image directories are collected by the graph above.
for p in inputs:
 rel=p.relative_to(repo).as_posix()
 forbidden=['/Source/TabControl/','/Source/Metro/','/Source/HexEditor/','/Source/SharpPcap/','/Terminals.External/Bdev/','/Terminals.External/Unified/','/Terminals.External/Render/','/Resources/Images/','/Resources/Libraries/']
 if any(x in rel for x in forbidden):raise RuntimeError('Uncleared legacy source input: '+rel)
extra={}
provenance=repo/'upstream/Terminals/Resources/Libraries/mstsc/GENERATION.json'
if provenance.exists():
 record=json.loads(provenance.read_text());extra['generated-rdp/GENERATION.json']=provenance
 for source in record.get('sources',[]):
  path=provenance.parent/source['name']
  if path.suffix!='.cs' or hashlib.sha256(path.read_bytes()).hexdigest().lower()!=source['sha256'].lower():raise RuntimeError('Generated interop source provenance mismatch')
  extra['generated-rdp/'+path.name]=path
identity=os.environ.get('GITHUB_SHA','')
if len(identity)!=40 or any(c not in '0123456789abcdefABCDEF' for c in identity):raise RuntimeError('Exact GITHUB_SHA build identity required')
output=Path(sys.argv[1] if len(sys.argv)>1 else repo/'source-output');output.mkdir(parents=True,exist_ok=True)
manifest={'build':identity,'projects':sorted(str(x.relative_to(repo)).replace('\\','/') for x in projects),'files':{str(p.relative_to(repo)).replace('\\','/'):hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(inputs)},'externalBuildInputs':'NuGet package versions/hashes, official signed PuTTY downloads and generated Windows RDP interop are described in the included build recipe and provenance files.'}
manifest['files'].update({name:hashlib.sha256(path.read_bytes()).hexdigest() for name,path in extra.items()})
archive=output/('DeskPilot-'+identity[:8]+'-Source.zip')
with zipfile.ZipFile(archive,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=9) as z:
 for p in sorted(inputs):z.write(p,p.relative_to(repo).as_posix())
 for name,path in extra.items():z.write(path,name)
 z.writestr('LICENSE.md',(repo/'upstream/Terminals/LICENSE.md').read_text())
 z.writestr('SOURCE-MANIFEST.json',json.dumps(manifest,indent=2)+'\n')
 z.writestr('BUILD.txt',identity+'\n')
 z.writestr('README.md',(repo/'docs/release/BUILD-FROM-SOURCE.md').read_text())
print(str(archive));print('Reviewed source inputs:',len(inputs),'projects:',len(projects))
